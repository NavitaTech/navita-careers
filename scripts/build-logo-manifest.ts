/**
 * Lists the university logo files that actually exist, into src/data/logos.json.
 *
 * Without this the app had to discover logos by requesting every candidate
 * filename and seeing which 404'd - five extensions across nineteen
 * universities, which is ninety-five failed requests on every single load. On
 * the booth that is wasted time on first load and a console full of errors;
 * in testing it was enough to exhaust the browser's connection pool.
 *
 * Runs automatically before every build. Add a logo file, build, done.
 *
 * Run: npm run logos
 */
import { readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'

const root = (p: string) => resolve(process.cwd(), p)
const LOGO_DIR = root('public/assets/logos')
const OUT = root('src/data/logos.json')

const EXTENSIONS = ['svg', 'png', 'jpg', 'jpeg', 'webp']
/** Preferred first: vector scales to any booth screen without softening. */
const rank = (ext: string): number => EXTENSIONS.indexOf(ext)

const universities = JSON.parse(
  (await import('node:fs')).readFileSync(root('src/data/universities.json'), 'utf8'),
).universities as { id: string; short: string }[]

mkdirSync(LOGO_DIR, { recursive: true })
const files = existsSync(LOGO_DIR) ? readdirSync(LOGO_DIR) : []

const manifest: Record<string, string> = {}
for (const file of files) {
  const match = /^(.+)\.([a-z0-9]+)$/i.exec(file)
  if (!match) continue
  const [, id, ext] = match
  const extension = ext.toLowerCase()
  if (!EXTENSIONS.includes(extension)) continue
  // Keep the best format when a university has more than one file.
  const current = manifest[id]
  if (current && rank(current.split('.').pop()!.toLowerCase()) <= rank(extension)) continue
  manifest[id] = file
}

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      $comment:
        'Generated by scripts/build-logo-manifest.ts from public/assets/logos/. Do not edit by hand - add the file and rebuild.',
      logos: manifest,
    },
    null,
    2,
  )}\n`,
)

const known = new Set(Object.keys(manifest))
const missing = universities.filter((u) => !known.has(u.id))
const extra = [...known].filter((id) => !universities.some((u) => u.id === id))

console.log(`Logo manifest -> src/data/logos.json`)
console.log(`  found   : ${Object.keys(manifest).length} file(s)`)
if (missing.length) {
  console.log(`  missing : ${missing.length} university logo(s) still to supply`)
  console.log(`            ${missing.map((u) => u.id).join(', ')}`)
}
if (extra.length) {
  console.log(`  unused  : ${extra.join(', ')} (no university with that id)`)
}
